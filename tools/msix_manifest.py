"""AppxManifest.xml of the Store edition (MSIX), from noirpad/__version__.py.

    .venv\\Scripts\\python.exe tools\\msix_manifest.py <output file>

build-msix.ps1 writes it into the package layout. Identity from Partner
Center (ROADMAP N1.9). Version: X.Y.Z.0 (the Store reserves the fourth
number; it is always 0).

MinVersion 10.0.17763.0 (Windows 10 1809 / Enterprise LTSC 2019):
  * Python 3.14 "supports Windows 10 and newer", and only Windows versions
    Microsoft still has under extended support (PEP 11; docs.python.org/3.14/
    using/windows.html, "Supported Windows versions"). The oldest Windows 10
    build still in extended support is Enterprise LTSC 2019 = 10.0.17763.
  * WebView2 runs on Windows 10 1709 (10.0.16299) and later
    (learn.microsoft.com/microsoft-edge/webview2, "Supported Windows versions").
  The higher of the two wins. MaxVersionTested: the newest Windows SDK used
  here (10.0.26100, Windows 11 24H2).
"""

import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import make_icons  # noqa: E402

IDENTITY_NAME = "krystof02.NoirPad"
PUBLISHER = "CN=7A230D16-A4F0-44D2-9725-8DF77823543E"
PUBLISHER_DISPLAY_NAME = "Arcly Studio"
MIN_VERSION = "10.0.17763.0"
MAX_VERSION_TESTED = "10.0.26100.0"
TILE_BACKGROUND = "transparent"
SPLASH_BACKGROUND = "#0e0e10"
DESCRIPTION = "Markdown notes you can lock with a password."
LANGUAGES = ("en-us", "cs-cz")


def app_version() -> str:
    text = (ROOT / "noirpad" / "__version__.py").read_text(encoding="utf-8")
    return re.search(r'^__version__ = "([^"]+)"', text, re.M).group(1)


def msix_version(version: str) -> str:
    """"1.1.0" -> "1.1.0.0". Exactly three numbers in, fourth always 0."""
    parts = version.split(".")
    if len(parts) != 3 or not all(p.isdigit() for p in parts):
        raise ValueError(f"version must be X.Y.Z, got {version!r}")
    if any(int(p) > 65535 for p in parts):
        raise ValueError(f"MSIX version parts must be <= 65535: {version!r}")
    return ".".join(str(int(p)) for p in parts) + ".0"


def manifest(version: str) -> str:
    a = make_icons.STORE_DIR.split("/")[-1]          # "Assets"
    langs = "\n".join(f'    <Resource Language="{lang}"/>' for lang in LANGUAGES)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/msix_manifest.py from noirpad/__version__.py. Do not edit. -->
<Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"
         xmlns:uap="http://schemas.microsoft.com/appx/manifest/uap/windows10"
         xmlns:rescap="http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities"
         IgnorableNamespaces="uap rescap">
  <Identity Name="{IDENTITY_NAME}" Publisher="{PUBLISHER}" Version="{msix_version(version)}" ProcessorArchitecture="x64"/>
  <Properties>
    <DisplayName>NoirPad</DisplayName>
    <PublisherDisplayName>{escape(PUBLISHER_DISPLAY_NAME)}</PublisherDisplayName>
    <Logo>{a}\\StoreLogo.png</Logo>
  </Properties>
  <Dependencies>
    <TargetDeviceFamily Name="Windows.Desktop" MinVersion="{MIN_VERSION}" MaxVersionTested="{MAX_VERSION_TESTED}"/>
  </Dependencies>
  <Resources>
{langs}
  </Resources>
  <Applications>
    <Application Id="NoirPad" Executable="NoirPad.exe" EntryPoint="Windows.FullTrustApplication">
      <uap:VisualElements DisplayName="NoirPad" Description="{escape(DESCRIPTION)}"
                          BackgroundColor="{TILE_BACKGROUND}"
                          Square150x150Logo="{a}\\Square150x150Logo.png" Square44x44Logo="{a}\\Square44x44Logo.png">
        <uap:DefaultTile Wide310x150Logo="{a}\\Wide310x150Logo.png" Square310x310Logo="{a}\\Square310x310Logo.png"
                         Square71x71Logo="{a}\\Square71x71Logo.png" ShortName="NoirPad"/>
        <uap:SplashScreen Image="{a}\\SplashScreen.png" BackgroundColor="{SPLASH_BACKGROUND}"/>
      </uap:VisualElements>
    </Application>
  </Applications>
  <Capabilities>
    <rescap:Capability Name="runFullTrust"/>
  </Capabilities>
</Package>
"""


def main(argv: list) -> int:
    if len(argv) != 1:
        print(__doc__.splitlines()[2].strip(), file=sys.stderr)
        return 2
    text = manifest(app_version())
    Path(argv[0]).write_text(text, encoding="utf-8")
    print(f"{argv[0]} (Version {msix_version(app_version())})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
