"""N8: THIRD-PARTY-NOTICES.txt is complete, current and shipped.

The file is generated by tools/third_party_notices.py from the pinned
dependencies; only its theme palette section is written by hand. build.ps1
stops when it is missing or out of date (same check as here).
"""

import json
import re
import sys

import pytest

from conftest import ROOT

sys.path.insert(0, str(ROOT / "tools"))
import third_party_notices as tpn  # noqa: E402

NOTICES = ROOT / "THIRD-PARTY-NOTICES.txt"


def _text():
    return NOTICES.read_bytes().decode("utf-8").replace("\r\n", "\n")


def test_file_is_current(capsys):
    assert tpn.main(["--check"]) == 0, capsys.readouterr().err


def test_every_runtime_package_and_vendor_library_is_listed():
    text = _text()
    for name, pin in tpn._pins():
        assert re.search(rf"^{re.escape(name)} {re.escape(pin)}$", text, re.M | re.I), name
    for pkg in tpn.VENDOR_DIRS.values():
        assert re.search(rf"^{re.escape(pkg)} \d", text, re.M), pkg
    assert "Python 3.14" in text and "Microsoft Edge WebView2 SDK" in text


def test_palette_section_names_the_five_themes():
    section = tpn.palettes(_text())
    ids = re.findall(r"^NoirPad theme id: ([\w-]+)$", section, re.M)
    assert sorted(ids) == sorted(tpn.PALETTE_THEMES)
    assert section.count("License: MIT") == 5
    assert section.count("Permission is hereby granted, free of charge") == 5


def test_check_fails_when_out_of_date(monkeypatch, tmp_path, capsys):
    stale = tmp_path / "THIRD-PARTY-NOTICES.txt"
    stale.write_bytes(_text().replace("fastapi 0.136.0", "fastapi 0.0.1").encode())
    monkeypatch.setattr(tpn, "OUT", stale)
    assert tpn.main(["--check"]) == 1
    assert "out of date" in capsys.readouterr().err


def test_check_fails_when_missing(monkeypatch, tmp_path, capsys):
    monkeypatch.setattr(tpn, "OUT", tmp_path / "THIRD-PARTY-NOTICES.txt")
    assert tpn.main(["--check"]) == 1
    assert "missing" in capsys.readouterr().err


def test_check_fails_without_the_palette_section(monkeypatch, tmp_path, capsys):
    broken = tmp_path / "THIRD-PARTY-NOTICES.txt"
    broken.write_text(_text().replace(tpn.PALETTES_BEGIN, "x"), encoding="utf-8")
    monkeypatch.setattr(tpn, "OUT", broken)
    assert tpn.main(["--check"]) == 1
    assert "palette section is missing" in capsys.readouterr().err


def test_a_new_pin_makes_it_stale(monkeypatch):
    pins = tpn._pins()
    monkeypatch.setattr(tpn, "_pins", lambda: [*pins, ("not-a-real-package-np", "1.0")])
    with pytest.raises(tpn.NoticeError, match="not installed"):
        tpn.build(_text())


def test_build_checks_and_ships_it():
    build = (ROOT / "build.ps1").read_text(encoding="utf-8-sig")
    check = build.index(r"tools\third_party_notices.py --check")
    assert check < build.index("PyInstaller (onedir)")
    assert re.search(r"third_party_notices\.py --check\s*\n\s*if \(\$LASTEXITCODE -ne 0\) \{ Fail", build)
    spec = (ROOT / "noirpad.spec").read_text(encoding="utf-8")
    assert '(str(ROOT / "THIRD-PARTY-NOTICES.txt"), ".")' in spec and '(str(ROOT / "LICENSE"), ".")' in spec
    iss = (ROOT / "installer.iss").read_text(encoding="utf-8-sig")
    assert re.search(r'^Source: "THIRD-PARTY-NOTICES\.txt"; DestDir: "\{app\}"', iss, re.M)
    assert re.search(r'^Source: "LICENSE"; DestDir: "\{app\}"; DestName: "LICENSE\.txt"', iss, re.M)
    # The smoke test of the built exe asks for them too (bundle path, N1.7).
    smoke = (ROOT / "tools" / "smoke_test.ps1").read_text(encoding="utf-8-sig")
    assert "/api/licenses" in smoke and "BEGIN THEME PALETTES" in smoke


def test_api_serves_both_texts(client):
    data = client.get("/api/licenses").json()
    assert data["license"].replace("\r\n", "\n").splitlines()[2] == "Copyright (c) 2026 Arcly Studio"
    assert data["notices"].replace("\r\n", "\n") == _text()


# ---- N1.10: Rust crates inside the wheels -------------------------------------

import importlib.metadata as md  # noqa: E402

import rust_notices  # noqa: E402  (tools/ is on sys.path above)

RUST_DISTS = ("cryptography", "pydantic_core")


@pytest.mark.parametrize("name", RUST_DISTS)
def test_every_crate_of_the_sbom_is_listed(name):
    """The wheel's own SBOM is the list of what is compiled in: every crate and its licence."""
    dist = md.distribution(name)
    sbom = rust_notices.sbom_path(dist)
    assert sbom is not None
    crates = rust_notices.crates(sbom)
    assert len(crates) > 10
    text = _text()
    start = text.index(f"Rust crates in {dist.metadata['Name']} {dist.version}\n")
    section = text[start:text.index("\n" + "-" * 79 + "\n[", start)]
    for crate, version, expr, _sha in crates:
        assert re.search(rf"^  {re.escape(crate)} {re.escape(version)}: {re.escape(expr)}", section, re.M), crate


def test_every_crate_has_a_licence_text():
    for name in RUST_DISTS:
        dist = md.distribution(name)
        data = json.loads(rust_notices.out_path(dist.metadata["Name"], dist.version).read_text(encoding="utf-8"))
        for c in data["crates"]:
            assert c["files"] and all(t.strip() for _, t in c["files"]), c["name"]
            assert c["used"] == rust_notices.choose(c["license"]) or c["files"][0][0] == rust_notices.NO_FILE


def test_openssl_inside_cryptography_is_listed():
    text = _text()
    assert re.search(r"^  OpenSSL \d+\.\d+\.\d+: Apache-2\.0", text, re.M)
    assert re.search(r"^\[OpenSSL \d+\.\d+\.\d+\]\n\s+Apache License", text, re.M)


@pytest.mark.parametrize("expr, used", [
    ("MIT OR Apache-2.0", ["MIT"]),
    ("Apache-2.0 OR GPL-2.0-only", ["Apache-2.0"]),
    ("(MIT OR Apache-2.0) AND Unicode-3.0", ["MIT", "Unicode-3.0"]),
    ("Apache-2.0 WITH LLVM-exception", ["Apache-2.0"]),
    ("Unlicense OR MIT", ["MIT"]),
    ("BSD-2-Clause OR Apache-2.0 OR MIT", ["MIT"]),
])
def test_licence_choice(expr, used):
    assert rust_notices.choose(expr) == used


def test_choice_never_takes_a_copyleft_licence_alone():
    with pytest.raises(rust_notices.RustNoticeError):
        rust_notices.choose("GPL-2.0-only")


def test_a_changed_crate_list_makes_it_stale(monkeypatch):
    """Bumping cryptography without refreshing tools/notices/rust fails the build."""
    real = rust_notices.crates
    monkeypatch.setattr(rust_notices, "crates", lambda sbom: [*real(sbom), ("new-crate", "1.0.0", "MIT", "0" * 64)])
    with pytest.raises(tpn.NoticeError, match="does not match the SBOM"):
        tpn.build(_text())


def test_a_missing_crate_file_makes_it_fail(monkeypatch, tmp_path):
    monkeypatch.setattr(rust_notices, "OUT_DIR", tmp_path)
    with pytest.raises(tpn.NoticeError, match=r"is missing: run tools.rust_notices.py"):
        tpn.build(_text())
